#!/usr/bin/env python3
"""Rebuild data/zip_market.json from Zillow Research's public ZIP-level CSVs.

Sources (free, published by Zillow Research for public use; attribution is shown in the app):
  ZORI  Zillow Observed Rent Index, all homes + multifamily, smoothed, by ZIP
  ZHVI  Zillow Home Value Index, single-family + condo, middle tier, by ZIP

Usage: python scripts/update_market_data.py [--from-dir DIR]   (DIR holds zori.csv and zhvi.csv)
Review the diff and the as_of dates before committing.
"""

import argparse
import csv
import http.client
import json
import sys
import time
import urllib.request
from pathlib import Path

URLS = {
    "zori": "https://files.zillowstatic.com/research/public_csvs/zori/Zip_zori_uc_sfrcondomfr_sm_month.csv",
    "zhvi": "https://files.zillowstatic.com/research/public_csvs/zhvi/Zip_zhvi_uc_sfrcondo_tier_0.33_0.67_sm_sa_month.csv",
}
OUT = Path(__file__).resolve().parent.parent / "data" / "zip_market.json"


def download(url: str, attempts: int = 4) -> str:
    """Large CSVs occasionally drop mid-transfer; retry rather than write a partial snapshot."""
    last = None
    for _ in range(attempts):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "DealScope-data-refresh"})
            return urllib.request.urlopen(req, timeout=120).read().decode("utf-8")
        except (OSError, http.client.HTTPException) as exc:
            last = exc
            time.sleep(2)
    raise SystemExit(f"download failed after {attempts} attempts: {last}")


def load(name: str, src_dir: Path = None) -> list:
    if src_dir:
        text = (src_dir / f"{name}.csv").read_text()
    else:
        text = download(URLS[name])
    return list(csv.reader(text.splitlines()))


def latest(rows: list) -> tuple:
    """Return ({zip: (value, state)}, as_of 'YYYY-MM') using each ZIP's most recent value."""
    header = rows[0]
    zip_i, state_i = header.index("RegionName"), header.index("State")
    month_cols = [i for i, h in enumerate(header) if h[:2] == "20" and len(h) == 10]
    as_of = header[month_cols[-1]][:7]
    out = {}
    for row in rows[1:]:
        values = [row[i] for i in month_cols if row[i]]
        if not values or not row[zip_i].isdigit():
            continue
        # Skip stale series: require a value in the last 3 months.
        if not any(row[i] for i in month_cols[-3:]):
            continue
        out[row[zip_i].zfill(5)] = (round(float(values[-1])), row[state_i])
    return out, as_of


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--from-dir", type=Path)
    args = parser.parse_args()
    rent, rent_as_of = latest(load("zori", args.from_dir))
    value, value_as_of = latest(load("zhvi", args.from_dir))
    zips = {}
    for z in sorted(set(rent) | set(value)):
        zips[z] = [
            rent.get(z, (None,))[0],
            value.get(z, (None,))[0],
            (rent.get(z) or value.get(z))[1],
        ]
    payload = {
        "_comment": "Generated by scripts/update_market_data.py. "
        "Entry: zip -> [typical monthly rent USD, typical home value USD, state].",
        "rent": {
            "name": "Zillow Observed Rent Index (ZORI)",
            "as_of": rent_as_of,
            "url": "https://www.zillow.com/research/data/",
        },
        "value": {
            "name": "Zillow Home Value Index (ZHVI)",
            "as_of": value_as_of,
            "url": "https://www.zillow.com/research/data/",
        },
        "zips": zips,
    }
    OUT.write_text(json.dumps(payload, separators=(",", ":")) + "\n")
    print(
        f"wrote {OUT} ({OUT.stat().st_size // 1024} KB): {len(zips)} ZIPs, "
        f"rent as of {rent_as_of}, value as of {value_as_of}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
